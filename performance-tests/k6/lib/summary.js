const thresholdStatus = (data) => {
  const results = Object.values(data.metrics || {}).flatMap((metric) =>
    Object.values(metric.thresholds || {}),
  );
  if (results.length === 0) return "NO_THRESHOLDS";
  return results.every((result) => result.ok) ? "PASS" : "FAIL";
};

export function buildSummary(data) {
  const status = thresholdStatus(data);
  const metrics = data.metrics || {};
  const requestCount = metrics.http_reqs?.values?.count;
  const requestRate = metrics.http_reqs?.values?.rate;
  const p95 = metrics.http_req_duration?.values?.["p(95)"];
  const p99 = metrics.http_req_duration?.values?.["p(99)"];
  const failedRate = metrics.http_req_failed?.values?.rate;
  const checkRate = metrics.checks?.values?.rate;
  const dropped = metrics.dropped_iterations?.values?.count;
  const value = (input, suffix = "") =>
    Number.isFinite(input) ? `${Number(input).toFixed(2)}${suffix}` : "NOT_AVAILABLE";
  const output = {
    stdout: [
      "",
      `k6 threshold result: ${status}`,
      `http_reqs: ${Number.isFinite(requestCount) ? requestCount : "NOT_AVAILABLE"}`,
      `http_reqs rate: ${value(requestRate, " rps")}`,
      `http_req_duration p(95): ${value(p95, " ms")}`,
      `http_req_duration p(99): ${value(p99, " ms")}`,
      `http_req_failed: ${value(Number.isFinite(failedRate) ? failedRate * 100 : failedRate, "%")}`,
      `dropped_iterations: ${Number.isFinite(dropped) ? dropped : "NOT_AVAILABLE"}`,
      `checks: ${value(Number.isFinite(checkRate) ? checkRate * 100 : checkRate, "%")}`,
      "Detailed artifacts are generated by performance-tests/k6/scripts/run.mjs.",
      "",
    ].join("\n"),
  };

  if (__ENV.SUMMARY_PATH) {
    output[__ENV.SUMMARY_PATH] = JSON.stringify(data, null, 2);
  }
  return output;
}
